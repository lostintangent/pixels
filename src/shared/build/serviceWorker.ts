import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readdir, readFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

/**
 * Every file the playground's service worker should precache, with a version derived from their
 * contents so an unchanged build is a no-op update and any changed byte, including `index.html`'s
 * unhashed name, rotates the cache.
 */
export interface Manifest {
  version: string;
  shellUrl: string;
  urls: string[];
}

/**
 * Builds the precache manifest from a build's emitted files. `base` prefixes every file into the
 * URL the browser will actually request (`/pixels/assets/x.js`, not `assets/x.js`). `sw.js` itself
 * is never included, so the worker never tries to cache or version itself.
 */
export function createManifest(
  base: string,
  files: { fileName: string; content: string | Uint8Array }[],
): Manifest {
  const sorted = files
    .filter((file) => file.fileName !== 'sw.js')
    .sort((a, b) => (a.fileName < b.fileName ? -1 : 1));
  const hash = createHash('sha256');
  for (const file of sorted) {
    hash.update(file.fileName);
    hash.update(typeof file.content === 'string' ? file.content : Buffer.from(file.content));
  }
  return {
    version: hash.digest('hex').slice(0, 16),
    shellUrl: `${base}index.html`,
    urls: sorted.map((file) => `${base}${file.fileName}`),
  };
}

/**
 * The service worker's own source. Every cache it owns is named `pixels-app-<version>`, so
 * `activate` can tell its own caches from another `lostintangent.github.io` project's sharing the
 * origin without guessing. Install fetches with `cache: 'reload'`, bypassing Pages' HTTP cache so
 * a precache never mixes an old `index.html` with chunks a new deploy renamed. A new worker waits
 * rather than taking over open tabs; `message` lets a page opt in once it has saved and is ready
 * to reload.
 *
 * `self.clients.claim()` in `activate` hands every open tab to the new worker at once, including
 * ones that haven't reloaded, because a single scope has one controller. Such a tab's own
 * already-fetched JS keeps running, but a *new* lazy import it fetches later is now a request the
 * new worker's fetch handler answers, and the new cache never has that old, still content-hashed
 * filename. So `activate` deletes every cache older than the one just before it rather than every
 * other `pixels-app-` cache: `caches.keys()` returns them in creation order, so keeping the single
 * newest stale entry preserves exactly the version an unreloaded tab's in-flight chunks still
 * need, and the fetch handler's global `caches.match` falls through to it, while bounding storage
 * at two versions.
 *
 * `install` stores each precached response with its `Vary` header stripped, instead of the
 * simpler `cache.addAll`. A CORS-aware static server's `Vary: Origin` otherwise makes `cache.match`
 * reject every real `<script crossorigin>`/`<link crossorigin>` request, because that tag always
 * sends an Origin header while this same-origin install-time fetch never does; the Cache API then
 * treats them as different variants and falls through to the network, which fails offline. Every
 * precached file is content-hashed and immutable for this version, so no header-based variant
 * ever legitimately applies, and `ignoreVary` on both `fetch` lookups is a second, independent
 * layer against the same class of mismatch.
 */
export function renderServiceWorker({ version, shellUrl, urls }: Manifest): string {
  return `// Generated by src/shared/build/serviceWorker.ts. Do not edit.
const PREFIX = 'pixels-app-';
const CACHE = PREFIX + ${JSON.stringify(version)};
const SHELL_URL = ${JSON.stringify(shellUrl)};
const PRECACHE_URLS = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      Promise.all(
        PRECACHE_URLS.map((url) =>
          fetch(new Request(url, { cache: 'reload' })).then((response) => {
            if (!response.ok) throw new Error(\`precache fetch failed for \${url}: \${response.status}\`);
            // Strip Vary before storing. A host that varies by Origin (any CORS-aware static
            // server) made cache.match reject every <script crossorigin>/<link crossorigin>
            // request here, because that tag always sends an Origin header while this same-origin
            // install-time fetch never does, and Cache's own Vary comparison then counts them as
            // different variants, a miss that silently fell through to the network and failed
            // offline. Every precached file is content-hashed and immutable for this version, so
            // no header-based variant ever applies; a plain URL match is always correct.
            const headers = new Headers(response.headers);
            headers.delete('vary');
            return cache.put(
              url,
              new Response(response.body, { status: response.status, statusText: response.statusText, headers }),
            );
          }),
        ),
      ),
    ),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => {
        const stale = keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE);
        // The most recently created stale cache is the version a not-yet-reloaded tab is still
        // running; every older one is unreachable from any open tab and safe to drop.
        const keep = stale.at(-1);
        return Promise.all(stale.filter((key) => key !== keep).map((key) => caches.delete(key)));
      })
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  // A \`no-store\` fetch is Reload's own reachability check: it must reach the network, offline or
  // not, or the check can't tell a live deploy from a stale cache answering for it.
  if (request.method !== 'GET' || request.cache === 'no-store') return;
  if (request.mode === 'navigate') {
    // The shell's URL never changes between versions, so a navigation must read it from this
    // worker's own current cache, never the global multi-cache lookup below, or an unreloaded
    // tab's leftover old cache could answer a fresh navigation with a stale shell.
    event.respondWith(
      caches
        .open(CACHE)
        .then((cache) => cache.match(SHELL_URL, { ignoreVary: true }))
        .then((cached) => cached || fetch(request)),
    );
    return;
  }
  // Every other request is content-hashed, so a name collision across versions can't happen; the
  // global lookup searching every cache is what lets an unreloaded tab's old-named lazy chunk
  // still resolve from the one retained stale cache above. \`ignoreVary\` is belt-and-suspenders
  // alongside the Vary stripping above, in case some host varies by a header install never sees.
  event.respondWith(
    caches.match(request, { ignoreVary: true }).then((cached) => cached || fetch(request)),
  );
});
`;
}

/** Every file under `dir`, as a path relative to it, skipping it entirely if it doesn't exist. */
async function filesUnder(dir: string): Promise<{ fileName: string; content: Buffer }[]> {
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  const files = entries.filter((entry) => entry.isFile());
  return Promise.all(
    files.map(async (entry) => ({
      fileName: relative(dir, join(entry.parentPath, entry.name)),
      content: await readFile(join(entry.parentPath, entry.name)),
    })),
  );
}

/**
 * Emits \`sw.js\` for the playground build only. A plain \`vite build\` (used by \`perf\`, \`golden\`,
 * and the other production-preview harnesses) serves from \`/\` and must stay untouched, since
 * registering a service worker there would start intercepting those harnesses' own fetches.
 * \`build:playground\` is the only build that passes a non-root \`--base\`, so that's the signal.
 * \`generateBundle\` runs after every other plugin's, including Vite's own HTML emission, so the
 * bundle this sees already contains \`index.html\` alongside every chunk and asset. \`public/\`'s
 * files (\`favicon.svg\`) never pass through Rollup at all, Vite copies them straight to \`outDir\`,
 * so they're read from disk here instead of off the bundle.
 */
export function serviceWorker(): Plugin {
  let base = '/';
  let publicDir = '';
  return {
    name: 'pixels-service-worker',
    apply: 'build',
    configResolved(config) {
      base = config.base;
      publicDir = config.publicDir;
    },
    generateBundle: {
      order: 'post',
      async handler(_options, bundle) {
        if (base === '/') return;
        const bundled = Object.values(bundle).map((item) => ({
          fileName: item.fileName,
          content: item.type === 'asset' ? item.source : item.code,
        }));
        const bundledNames = new Set(bundled.map((file) => file.fileName));
        // A bundled file wins over a public one of the same name, matching Vite's own output.
        const fromPublic = (await filesUnder(publicDir)).filter(
          (file) => !bundledNames.has(file.fileName),
        );
        const manifest = createManifest(base, [...bundled, ...fromPublic]);
        this.emitFile({ type: 'asset', fileName: 'sw.js', source: renderServiceWorker(manifest) });
      },
    },
  };
}
